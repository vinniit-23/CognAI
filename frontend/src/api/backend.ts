export const notifyConnection = async (userId: string): Promise<{ ok: boolean }> => {
  if (mockMode) {
    await new Promise(resolve => setTimeout(resolve, 500));
    return { ok: true };
  }

  try {
    const response = await api.post('/notify-connection', { user_id: userId });
    return response.data;
  } catch (error) {
    console.error('Notify connection API error:', error);
    throw new Error('Failed to notify backend of Gmail connection.');
  }
};