import axios from 'axios';

const BACKEND_URL = import.meta.env.VITE_BACKEND_URL || 'http://127.0.0.1:8000';

const api = axios.create({
  baseURL: BACKEND_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

export interface ChatResponse {
  ai_response: string;
}

export interface EmailMessage {
  id: string;
  threadId: string;
  snippet: string;
  from: string;
  subject: string;
  date: string;
}

export interface EmailsResponse {
  messages: EmailMessage[];
  nextPageToken?: string;
  resultSizeEstimate: number;
}

// Mock mode for development when backend is not available
let mockMode = false;

export const setMockMode = (enabled: boolean) => {
  mockMode = enabled;
};

export const postChat = async (userPrompt: string, userId?: string): Promise<ChatResponse> => {
  if (mockMode) {
    // Mock response for development
    await new Promise(resolve => setTimeout(resolve, 1000 + Math.random() * 2000));
    return {
      ai_response: `This is a mock response to: "${userPrompt}". In production, this would be generated by your AI backend. The user ID is: ${userId || 'not provided'}.`,
    };
  }

  try {
    const response = await api.post('/chat', {
      user_prompt: userPrompt,
      ...(userId && { user_id: userId }),
    });
    return response.data;
  } catch (error) {
    console.error('Chat API error:', error);
    throw new Error('Failed to send message. Please try again.');
  }
};

